const LANG_KEY = "preferredLanguage";
const LEGACY_LANG_KEY = "aerovista-lang";
const SUPPORTED_LANGS = Object.keys(languages);

const EASTERN_DIGITS = "٠١٢٣٤٥٦٧٨٩";

function toArabicDigits(value) {
  return String(value).replace(/[0-9]/g, (d) => EASTERN_DIGITS[d]);
}

function formatPhoneDisplay(phone, lang) {
  let digits = String(phone).replace(/[^\d+]/g, "");
  if (!digits.startsWith("+")) digits = "+" + digits.replace(/^\+*/, "");

  const m = digits.match(/^(\+\d{2})(\d{3})(\d{3})(\d{4})$/);
  let formatted = m ? `${m[1]} ${m[2]} ${m[3]} ${m[4]}` : digits;

  if (lang === "ar") formatted = toArabicDigits(formatted);

  return "\u202A" + formatted + "\u202C";
}

function getLang() {
  const saved = localStorage.getItem(LANG_KEY) || localStorage.getItem(LEGACY_LANG_KEY);
  return SUPPORTED_LANGS.includes(saved) ? saved : "en";
}

function t(key) {
  const lang = getLang();
  return (translations[lang] && translations[lang][key]) || translations.en[key] || key;
}

function updateLocalizedNumbers(lang) {
  if (typeof apartmentConfig !== "undefined") {
    const c = apartmentConfig;
    const pairs = [
      ["footerPhone", c.phoneNumber],
      ["footerPhone2", c.phoneNumber2],
      ["footerWhatsapp", c.phoneNumber],
      ["footerWhatsapp2", c.phoneNumber2],
    ];
    pairs.forEach(([id, phone]) => {
      const el = document.getElementById(id);
      if (!el || !phone) return;
      el.textContent = formatPhoneDisplay(phone, lang);
      el.setAttribute("dir", "ltr");
      el.classList.add("phone-ltr");
    });
  }

  document.querySelectorAll(".info-value[data-number]").forEach((el) => {
    const raw = el.getAttribute("data-number");
    el.textContent = lang === "ar" ? toArabicDigits(raw) : raw;
  });

  const yearEl = document.getElementById("currentYear");
  if (yearEl) {
    const year = String(new Date().getFullYear());
    yearEl.textContent = lang === "ar" ? toArabicDigits(year) : year;
  }
}

function updateLangDropdown(lang) {
  const meta = languages[lang] || languages.en;
  const flagEl = document.getElementById("langCurrentFlag");
  const labelEl = document.getElementById("langCurrentLabel");
  const toggle = document.getElementById("langDropdownToggle");

  if (flagEl) {
    flagEl.src = meta.flag;
    flagEl.alt = "";
  }
  if (labelEl) labelEl.textContent = meta.label;

  if (toggle) {
    toggle.setAttribute("aria-label", t("langSwitcher"));
    toggle.setAttribute("aria-expanded", "false");
  }

  document.querySelectorAll(".lang-option").forEach((btn) => {
    const code = btn.getAttribute("data-lang");
    const active = code === lang;
    btn.classList.toggle("active", active);
    btn.setAttribute("aria-selected", active ? "true" : "false");
    const img = btn.querySelector(".lang-flag");
    if (img && languages[code]) img.src = languages[code].flag;
  });

  const menu = document.getElementById("langDropdownMenu");
  if (menu) menu.hidden = true;

  const switcher = document.getElementById("langSwitcher");
  if (switcher) switcher.classList.remove("open");
}

function closeLangDropdown() {
  const switcher = document.getElementById("langSwitcher");
  const toggle = document.getElementById("langDropdownToggle");
  const menu = document.getElementById("langDropdownMenu");
  if (switcher) switcher.classList.remove("open");
  if (menu) menu.hidden = true;
  if (toggle) toggle.setAttribute("aria-expanded", "false");
}

function openLangDropdown() {
  const switcher = document.getElementById("langSwitcher");
  const toggle = document.getElementById("langDropdownToggle");
  const menu = document.getElementById("langDropdownMenu");
  if (switcher) switcher.classList.add("open");
  if (menu) menu.hidden = false;
  if (toggle) toggle.setAttribute("aria-expanded", "true");
}

function applyLanguage(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) lang = "en";
  localStorage.setItem(LANG_KEY, lang);
  localStorage.setItem(LEGACY_LANG_KEY, lang);

  const meta = languages[lang];
  const html = document.documentElement;
  html.lang = lang;
  html.dir = meta.dir;

  const dict = translations[lang] || translations.en;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key] != null) el.setAttribute("placeholder", dict[key]);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (dict[key] == null) return;
    el.setAttribute("aria-label", dict[key]);
    if (el.hasAttribute("title")) el.setAttribute("title", dict[key]);
  });

  document.querySelectorAll("[data-i18n-tooltip]").forEach((el) => {
    const key = el.getAttribute("data-i18n-tooltip");
    if (dict[key] != null) el.setAttribute("data-tooltip", dict[key]);
  });

  document.querySelectorAll("[data-i18n-label]").forEach((el) => {
    const key = el.getAttribute("data-i18n-label");
    if (dict[key] != null) el.setAttribute("data-label", dict[key]);
  });

  document.title = dict.pageTitle;
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute("content", dict.metaDescription);
  const ogTitle = document.querySelector('meta[property="og:title"]');
  if (ogTitle) ogTitle.setAttribute("content", dict.pageTitle);
  const ogDesc = document.querySelector('meta[property="og:description"]');
  if (ogDesc) ogDesc.setAttribute("content", dict.metaDescription);
  const ogLocale = document.querySelector('meta[property="og:locale"]');
  if (ogLocale) ogLocale.setAttribute("content", dict.ogLocale);
  const ogImageAlt = document.querySelector('meta[property="og:image:alt"]');
  if (ogImageAlt) ogImageAlt.setAttribute("content", dict.ogImageAlt);

  const cityEl = document.getElementById("footerCity");
  if (cityEl) cityEl.textContent = dict.footerCity;

  updateLocalizedNumbers(lang);
  updateLangDropdown(lang);
}

function initI18n() {
  const switcher = document.getElementById("langSwitcher");
  const toggle = document.getElementById("langDropdownToggle");
  const menu = document.getElementById("langDropdownMenu");

  if (toggle && menu) {
    toggle.addEventListener("click", (e) => {
      e.stopPropagation();
      const isOpen = switcher.classList.contains("open");
      if (isOpen) closeLangDropdown();
      else openLangDropdown();
    });

    menu.addEventListener("click", (e) => {
      const option = e.target.closest(".lang-option");
      if (!option) return;
      const lang = option.getAttribute("data-lang");
      if (lang) applyLanguage(lang);
    });

    document.addEventListener("click", (e) => {
      if (!switcher.contains(e.target)) closeLangDropdown();
    });

    document.addEventListener("keydown", (e) => {
      if (e.key === "Escape") closeLangDropdown();
    });

    toggle.addEventListener("keydown", (e) => {
      if (e.key === "ArrowDown" || e.key === "Enter" || e.key === " ") {
        e.preventDefault();
        openLangDropdown();
        const active = menu.querySelector(".lang-option.active") || menu.querySelector(".lang-option");
        if (active) active.focus();
      }
    });

    menu.addEventListener("keydown", (e) => {
      const options = [...menu.querySelectorAll(".lang-option")];
      const index = options.indexOf(document.activeElement);
      if (e.key === "ArrowDown") {
        e.preventDefault();
        options[(index + 1) % options.length]?.focus();
      } else if (e.key === "ArrowUp") {
        e.preventDefault();
        options[(index - 1 + options.length) % options.length]?.focus();
      } else if (e.key === "Escape") {
        closeLangDropdown();
        toggle.focus();
      } else if (e.key === "Enter" || e.key === " ") {
        e.preventDefault();
        document.activeElement?.click();
      }
    });
  }

  applyLanguage(getLang());
}

initI18n();
